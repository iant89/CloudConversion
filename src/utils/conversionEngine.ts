export class ConversionError extends Error {
  isCorrupted: boolean;
  constructor(message: string, isCorrupted = false) {
    super(message);
    this.name = 'ConversionError';
    this.isCorrupted = isCorrupted;
  }
}

function sleep(ms: number, signal: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal.aborted) {
      reject(new DOMException('Conversion cancelled by user', 'AbortError'));
      return;
    }
    const timer = window.setTimeout(() => {
      signal.removeEventListener('abort', onAbort);
      resolve();
    }, ms);
    const onAbort = () => {
      window.clearTimeout(timer);
      reject(new DOMException('Conversion cancelled by user', 'AbortError'));
    };
    signal.addEventListener('abort', onAbort, { once: true });
  });
}

function getStageLabel(
  progress: number,
  sourceExt: string,
  targetExt: string,
  category: string
): string {
  const src = sourceExt.toUpperCase();
  const dst = targetExt.toUpperCase();
  if (progress < 16) {
    return `Reading ${src} input stream & analyzing headers...`;
  }
  if (progress < 38) {
    if (category === 'video') return `Demuxing ${src} video/audio tracks...`;
    if (category === 'audio') return `Decoding ${src} PCM audio waveform...`;
    if (category === 'image') return `Decoding ${src} raster color channels...`;
    return `Parsing ${src} document structure & metadata...`;
  }
  if (progress < 78) {
    if (category === 'video') return `Transcoding video stream to ${dst} (H.264/AAC)...`;
    if (category === 'audio') return `Encoding audio stream to ${dst}...`;
    if (category === 'image') return `Rendering & compressing ${dst} image data...`;
    return `Converting & formatting ${dst} document layout...`;
  }
  if (progress < 94) {
    return `Muxing ${dst} container & writing metadata index...`;
  }
  return `Finalizing ${dst} output file...`;
}

/**
 * Generates a valid, spec-compliant PDF 1.4 binary buffer with accurate xref offsets
 */
function buildValidPdfBlob(title: string, lines: string[]): Blob {
  const sanitizePdfText = (str: string) =>
    str
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)')
      .replace(/[^\x20-\x7E]/g, ' ');

  const contentLines: string[] = [
    'BT',
    '/F1 16 Tf',
    '50 760 Td',
    `(${sanitizePdfText(title.slice(0, 75))}) Tj`,
    '/F1 10 Tf',
    '0 -24 Td',
    `(Generated by CloudConversion Engine - ${new Date().toISOString()}) Tj`,
    '0 -12 Td',
    '(--------------------------------------------------------------------------------) Tj',
  ];

  const maxLines = Math.min(lines.length, 42);
  for (let i = 0; i < maxLines; i++) {
    const line = sanitizePdfText(lines[i].slice(0, 90));
    contentLines.push('0 -15 Td');
    contentLines.push(`(${line}) Tj`);
  }
  contentLines.push('ET');

  const streamContent = contentLines.join('\n');
  const objects: string[] = [
    '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n',
    '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n',
    '3 0 obj\n<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 4 0 R >> >> /MediaBox [0 0 612 792] /Contents 5 0 R >>\nendobj\n',
    '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n',
    `5 0 obj\n<< /Length ${streamContent.length} >>\nstream\n${streamContent}\nendstream\nendobj\n`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(pdf.length);
    pdf += obj;
  }

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let i = 1; i < offsets.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1}\n/Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
}

/**
 * Decodes existing audio file if browser-supported or synthesizes a rich 4-second
 * melodic audio waveform (44.1kHz 16-bit PCM WAV) so converted audio files play in any audio player.
 */
async function buildPlayableAudioBlob(
  sourceFile: File,
  mimeType: string,
  durationSec = 4.0
): Promise<Blob> {
  const sampleRate = 44100;
  let channelData: Float32Array | null = null;

  if (
    sourceFile.type.startsWith('audio/') ||
    ['wav', 'mp3', 'ogg', 'flac', 'm4a', 'aac', 'webm'].some((ext) =>
      sourceFile.name.toLowerCase().endsWith(`.${ext}`)
    )
  ) {
    try {
      const AudioCtx =
        window.AudioContext ||
        (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      if (AudioCtx) {
        const ctx = new AudioCtx({ sampleRate });
        const arrayBuf = await sourceFile.arrayBuffer();
        const decoded = await ctx.decodeAudioData(arrayBuf.slice(0));
        const maxFrames = Math.min(decoded.length, sampleRate * 30);
        channelData = decoded.getChannelData(0).slice(0, maxFrames);
        await ctx.close();
      }
    } catch {
      // Fallback to synthesized waveform
    }
  }

  const numSamples = channelData ? channelData.length : Math.floor(sampleRate * durationSec);
  const numChannels = 1;
  const bytesPerSample = 2;
  const dataSize = numSamples * numChannels * bytesPerSample;
  const buffer = new ArrayBuffer(44 + dataSize);
  const view = new DataView(buffer);

  const writeStr = (offset: number, str: string) => {
    for (let i = 0; i < str.length; i++) {
      view.setUint8(offset + i, str.charCodeAt(i));
    }
  };

  writeStr(0, 'RIFF');
  view.setUint32(4, 36 + dataSize, true);
  writeStr(8, 'WAVE');
  writeStr(12, 'fmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, numChannels, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * numChannels * bytesPerSample, true);
  view.setUint16(32, numChannels * bytesPerSample, true);
  view.setUint16(34, 16, true);
  writeStr(36, 'data');
  view.setUint32(40, dataSize, true);

  if (channelData) {
    for (let i = 0; i < numSamples; i++) {
      const pcm = Math.max(-1, Math.min(1, channelData[i]));
      view.setInt16(44 + i * 2, pcm * 32767, true);
    }
  } else {
    const chords = [
      [261.63, 329.63, 392.0, 493.88],
      [220.0, 261.63, 329.63, 392.0],
      [174.61, 220.0, 261.63, 329.63],
      [196.0, 246.94, 293.66, 349.23],
    ];
    for (let i = 0; i < numSamples; i++) {
      const t = i / sampleRate;
      const chordIdx = Math.min(chords.length - 1, Math.floor((t / durationSec) * chords.length));
      const freqs = chords[chordIdx];
      const localT = (t % (durationSec / chords.length)) / (durationSec / chords.length);
      const env = Math.sin(Math.PI * localT) * 0.32;
      let val = 0;
      for (let c = 0; c < freqs.length; c++) {
        val += Math.sin(2 * Math.PI * freqs[c] * t) / freqs.length;
      }
      const pcm = Math.max(-1, Math.min(1, val * env));
      view.setInt16(44 + i * 2, pcm * 32767, true);
    }
  }

  return new Blob([buffer], { type: mimeType || 'audio/wav' });
}

/**
 * Records a playable video stream using HTML5 Canvas + MediaRecorder or falls back to ISO Base Media container.
 */
async function buildPlayableVideoBlob(
  item: ConversionQueueItem,
  mimeType: string
): Promise<Blob> {
  if (typeof MediaRecorder !== 'undefined') {
    try {
      const canvas = document.createElement('canvas');
      canvas.width = 640;
      canvas.height = 360;
      const ctx = canvas.getContext('2d');

      if (ctx && typeof canvas.captureStream === 'function') {
        const stream = canvas.captureStream(30);
        const candidates = [
          'video/mp4',
          'video/webm;codecs=vp9',
          'video/webm;codecs=vp8',
          'video/webm',
        ];
        const supportedMime =
          candidates.find((m) => MediaRecorder.isTypeSupported(m)) || '';

        const recorder = supportedMime
          ? new MediaRecorder(stream, { mimeType: supportedMime })
          : new MediaRecorder(stream);

        const chunks: BlobPart[] = [];
        recorder.ondataavailable = (e) => {
          if (e.data && e.data.size > 0) chunks.push(e.data);
        };

        const recordingPromise = new Promise<Blob>((resolve, reject) => {
          recorder.onstop = () => {
            resolve(new Blob(chunks, { type: mimeType || supportedMime || 'video/mp4' }));
          };
          recorder.onerror = (err) => reject(err);
        });

        recorder.start(100);

        const totalFrames = 45;
        for (let f = 0; f < totalFrames; f++) {
          const progress = f / (totalFrames - 1);
          const grad = ctx.createLinearGradient(0, 0, canvas.width, canvas.height);
          grad.addColorStop(0, '#141921');
          grad.addColorStop(1, '#232d3d');
          ctx.fillStyle = grad;
          ctx.fillRect(0, 0, canvas.width, canvas.height);

          for (let b = 0; b < 18; b++) {
            const barH =
              28 +
              Math.sin(progress * Math.PI * 4 + b * 0.55) * 22 +
              Math.cos(progress * Math.PI * 2 - b * 0.3) * 14;
            ctx.fillStyle = b % 2 === 0 ? '#c83e37' : '#3b82f6';
            ctx.fillRect(92 + b * 26, 235 - barH, 16, barH);
          }

          ctx.fillStyle = '#ffffff';
          ctx.font = 'bold 22px system-ui, sans-serif';
          ctx.textAlign = 'center';
          ctx.fillText(
            `${item.baseName}.${item.targetExt.toLowerCase()}`,
            canvas.width / 2,
            95
          );

          ctx.fillStyle = '#94a3b8';
          ctx.font = '14px system-ui, sans-serif';
          ctx.fillText(
            `Transcoded from .${item.sourceExt.toUpperCase()} → .${item.targetExt.toUpperCase()} (${(
              item.options.videoCodec || 'h264'
            ).toUpperCase()})`,
            canvas.width / 2,
            130
          );

          ctx.fillStyle = '#334155';
          ctx.fillRect(90, 275, 460, 8);
          ctx.fillStyle = '#28a745';
          ctx.fillRect(90, 275, 460 * progress, 8);

          ctx.fillStyle = '#e2e8f0';
          ctx.font = '12px monospace';
          ctx.fillText(
            `TIMECODE 00:00:0${(progress * 3).toFixed(2)} • ${
              item.options.videoResolution || '1920x1080'
            }`,
            canvas.width / 2,
            312
          );

          await new Promise((r) => setTimeout(r, 14));
        }

        recorder.stop();
        stream.getTracks().forEach((t) => t.stop());
        const recordedBlob = await recordingPromise;
        if (recordedBlob.size > 0) {
          return recordedBlob;
        }
      }
    } catch {
      // Fallback below
    }
  }

  const encoder = new TextEncoder();
  const metaText = JSON.stringify({
    converter: 'CloudConversion Transcode Engine',
    sourceFile: item.fileName,
    sourceFormat: item.sourceExt.toUpperCase(),
    targetFormat: item.targetExt.toUpperCase(),
    videoCodec: item.options.videoCodec || 'h264',
    resolution: item.options.videoResolution || 'original',
    audioCodec: item.options.audioCodec || 'aac',
    convertedAt: new Date().toISOString(),
  });
  const metaBytes = encoder.encode(metaText);
  const sliceSize = Math.min(item.file.size, 65536);
  const sourceSlice = new Uint8Array(await item.file.slice(0, sliceSize).arrayBuffer());

  const ftyp = new Uint8Array([
    0x00, 0x00, 0x00, 0x1c,
    0x66, 0x74, 0x79, 0x70,
    0x69, 0x73, 0x6f, 0x6d,
    0x00, 0x00, 0x02, 0x00,
    0x69, 0x73, 0x6f, 0x6d,
    0x69, 0x73, 0x6f, 0x32,
    0x61, 0x76, 0x63, 0x31,
    0x6d, 0x70, 0x34, 0x31,
  ].slice(0, 28));

  const freeBoxSize = 8 + metaBytes.length;
  const freeBox = new Uint8Array(freeBoxSize);
  const freeView = new DataView(freeBox.buffer);
  freeView.setUint32(0, freeBoxSize, false);
  freeBox.set([0x66, 0x72, 0x65, 0x65], 4);
  freeBox.set(metaBytes, 8);

  const mdatPayloadSize = Math.max(sourceSlice.length, 1024);
  const mdatBoxSize = 8 + mdatPayloadSize;
  const mdatBox = new Uint8Array(mdatBoxSize);
  const mdatView = new DataView(mdatBox.buffer);
  mdatView.setUint32(0, mdatBoxSize, false);
  mdatBox.set([0x6d, 0x64, 0x61, 0x74], 4);
  mdatBox.set(sourceSlice, 8);

  return new Blob([ftyp, freeBox, mdatBox], { type: mimeType });
}

async function convertToImageBlob(
  item: ConversionQueueItem,
  mimeType: string
): Promise<Blob> {
  const targetExt = item.targetExt.toLowerCase();

  const loadImage = (): Promise<HTMLImageElement | null> =>
    new Promise((resolve) => {
      if (
        !item.file.type.startsWith('image/') &&
        !['png', 'jpg', 'jpeg', 'webp', 'gif', 'bmp', 'svg', 'ico'].includes(item.sourceExt)
      ) {
        resolve(null);
        return;
      }
      const url = URL.createObjectURL(item.file);
      const img = new Image();
      img.onload = () => {
        URL.revokeObjectURL(url);
        resolve(img);
      };
      img.onerror = () => {
        URL.revokeObjectURL(url);
        resolve(null);
      };
      img.src = url;
    });

  const img = await loadImage();
  const width = item.options.imageResizeWidth || (img ? img.naturalWidth || 800 : 800);
  const height = item.options.imageResizeHeight || (img ? img.naturalHeight || 500 : 500);

  if (targetExt === 'svg') {
    const svgContent = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="#1b222c"/>
      <stop offset="100%" stop-color="#2c3748"/>
    </linearGradient>
  </defs>
  <rect width="100%" height="100%" rx="12" fill="url(#bg)"/>
  <rect x="24" y="24" width="${width - 48}" height="${height - 48}" rx="8" fill="none" stroke="#c83e37" stroke-width="2" stroke-dasharray="6 4"/>
  <text x="50%" y="44%" dominant-baseline="middle" text-anchor="middle" fill="#ffffff" font-family="system-ui, sans-serif" font-size="24" font-weight="bold">${item.baseName}.${targetExt}</text>
  <text x="50%" y="56%" dominant-baseline="middle" text-anchor="middle" fill="#94a3b8" font-family="system-ui, sans-serif" font-size="15">Converted from .${item.sourceExt.toUpperCase()} (${formatBytes(item.fileSize)}) via CloudConversion</text>
</svg>`;
    return new Blob([svgContent], { type: 'image/svg+xml' });
  }

  const canvas = document.createElement('canvas');
  canvas.width = Math.max(16, Math.min(4096, width));
  canvas.height = Math.max(16, Math.min(4096, height));
  const ctx = canvas.getContext('2d');

  if (ctx) {
    if (img) {
      if (targetExt === 'jpg' || targetExt === 'jpeg' || targetExt === 'bmp') {
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, canvas.width, canvas.height);
      }
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    } else {
      const grad = ctx.createLinearGradient(0, 0, canvas.width, canvas.height);
      grad.addColorStop(0, '#1b222c');
      grad.addColorStop(1, '#263244');
      ctx.fillStyle = grad;
      ctx.fillRect(0, 0, canvas.width, canvas.height);

      ctx.strokeStyle = '#c83e37';
      ctx.lineWidth = 4;
      ctx.strokeRect(24, 24, canvas.width - 48, canvas.height - 48);

      ctx.fillStyle = '#ffffff';
      ctx.font = 'bold 28px system-ui, sans-serif';
      ctx.textAlign = 'center';
      ctx.fillText(`${item.baseName}.${targetExt}`, canvas.width / 2, canvas.height / 2 - 16);

      ctx.fillStyle = '#cbd5e1';
      ctx.font = '16px system-ui, sans-serif';
      ctx.fillText(
        `Converted from ${item.fileName} (${formatBytes(item.fileSize)})`,
        canvas.width / 2,
        canvas.height / 2 + 24
      );
    }
  }

  const quality = Math.max(0.1, Math.min(1, (item.options.imageQuality ?? 90) / 100));
  const canvasMime =
    targetExt === 'jpg' || targetExt === 'jpeg'
      ? 'image/jpeg'
      : targetExt === 'webp'
      ? 'image/webp'
      : 'image/png';

  const blob = await new Promise<Blob | null>((resolve) =>
    canvas.toBlob((b) => resolve(b), canvasMime, quality)
  );

  return blob || new Blob(['IMAGE_DATA'], { type: mimeType });
}

async function convertDataOrDocumentBlob(
  item: ConversionQueueItem,
  mimeType: string
): Promise<Blob> {
  const targetExt = item.targetExt.toLowerCase();
  let rawText = '';
  try {
    const slice = item.file.slice(0, 1024 * 256);
    rawText = await slice.text();
    const nonPrintableRatio =
      (rawText.match(/[\x00-\x08\x0E-\x1F]/g)?.length || 0) / Math.max(1, rawText.length);
    if (nonPrintableRatio > 0.15) {
      rawText = `Source File: ${item.fileName}\nSource Format: ${item.sourceExt.toUpperCase()}\nOriginal Size: ${formatBytes(item.fileSize)}\nConverted Format: ${targetExt.toUpperCase()}\nConverted Timestamp: ${new Date().toISOString()}`;
    }
  } catch {
    rawText = `Source File: ${item.fileName}\nOriginal Size: ${formatBytes(item.fileSize)}`;
  }

  const lines = rawText.split(/\r?\n/).filter((l) => l.trim().length > 0);

  if (targetExt === 'pdf') {
    return buildValidPdfBlob(`${item.baseName}.${targetExt}`, [
      `Source Document: ${item.fileName} (${formatBytes(item.fileSize)})`,
      `Target Format: PDF (${item.options.pageSize || 'A4'} ${item.options.pageOrientation || 'portrait'})`,
      '',
      ...lines,
    ]);
  }

  if (targetExt === 'json') {
    if ((item.sourceExt === 'csv' || item.sourceExt === 'tsv') && lines.length >= 2) {
      const sep = item.sourceExt === 'tsv' ? '\t' : ',';
      const headers = lines[0].split(sep).map((h) => h.trim().replace(/^"|"$/g, ''));
      const records = lines.slice(1).map((line) => {
        const cols = line.split(sep).map((c) => c.trim().replace(/^"|"$/g, ''));
        const obj: Record<string, string> = {};
        headers.forEach((h, i) => {
          obj[h || `col_${i + 1}`] = cols[i] ?? '';
        });
        return obj;
      });
      return new Blob([JSON.stringify(records, null, 2)], { type: 'application/json' });
    }

    const payload = {
      fileName: `${item.baseName}.json`,
      convertedFrom: item.fileName,
      sourceFormat: item.sourceExt,
      originalSize: item.fileSize,
      convertedAt: new Date().toISOString(),
      content: lines,
    };
    return new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
  }

  if (targetExt === 'csv' || targetExt === 'tsv') {
    const sep = targetExt === 'tsv' ? '\t' : ',';
    try {
      const parsed = JSON.parse(rawText);
      if (Array.isArray(parsed) && parsed.length > 0 && typeof parsed[0] === 'object') {
        const keys = Object.keys(parsed[0]);
        const csvRows = [
          keys.join(sep),
          ...parsed.map((row: Record<string, unknown>) =>
            keys.map((k) => `"${String(row[k] ?? '').replace(/"/g, '""')}"`).join(sep)
          ),
        ];
        return new Blob([csvRows.join('\n')], { type: mimeType });
      }
    } catch {
      // Fallback
    }
    const csvContent = [
      ['line_number', 'source_file', 'content'].join(sep),
      ...lines.map((l, idx) =>
        [idx + 1, `"${item.fileName}"`, `"${l.replace(/"/g, '""')}"`].join(sep)
      ),
    ].join('\n');
    return new Blob([csvContent], { type: mimeType });
  }

  if (targetExt === 'html') {
    const escapedLines = lines
      .map(
        (l) =>
          `<p>${l
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')}</p>`
      )
      .join('\n      ');
    const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>${item.baseName} — Converted by CloudConversion</title>
  <style>
    body { font-family: system-ui, -apple-system, sans-serif; max-width: 820px; margin: 40px auto; padding: 0 24px; color: #1e293b; line-height: 1.6; }
    header { border-bottom: 2px solid #c83e37; padding-bottom: 12px; margin-bottom: 24px; }
    .meta { color: #64748b; font-size: 0.875rem; }
  </style>
</head>
<body>
  <header>
    <h1>${item.baseName}.${targetExt}</h1>
    <div class="meta">Converted from ${item.fileName} (${formatBytes(item.fileSize)})</div>
  </header>
  <main>
      ${escapedLines}
  </main>
</body>
</html>`;
    return new Blob([html], { type: 'text/html' });
  }

  if (targetExt === 'md') {
    const md = `# ${item.baseName}\n\n> Converted from \`${item.fileName}\` (${formatBytes(item.fileSize)})\n\n${lines.join('\n\n')}\n`;
    return new Blob([md], { type: 'text/markdown' });
  }

  if (targetExt === 'xml') {
    const xmlRows = lines
      .map(
        (l, idx) =>
          `  <entry index="${idx + 1}">${l
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')}</entry>`
      )
      .join('\n');
    const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<document source="${item.fileName}" convertedAt="${new Date().toISOString()}">\n${xmlRows}\n</document>`;
    return new Blob([xml], { type: 'application/xml' });
  }

  if (targetExt === 'yaml') {
    const yaml = `source_file: "${item.fileName}"\nsource_format: "${item.sourceExt}"\nconverted_at: "${new Date().toISOString()}"\ncontent:\n${lines
      .map((l) => `  - ${JSON.stringify(l)}`)
      .join('\n')}\n`;
    return new Blob([yaml], { type: 'text/yaml' });
  }

  if (targetExt === 'rtf') {
    const rtfBody = lines.map((l) => `${l.replace(/[\\{}]/g, '')}\\par`).join('\n');
    const rtf = `{\\rtf1\\ansi\\deff0 {\\fonttbl {\\f0 Helvetica;}}\n\\f0\\fs24 \\b ${item.baseName}.${targetExt}\\b0\\par\\par\n${rtfBody}\n}`;
    return new Blob([rtf], { type: 'application/rtf' });
  }

  const outputText = [
    `=== ${item.baseName}.${targetExt} ===`,
    `Converted from: ${item.fileName} (${formatBytes(item.fileSize)})`,
    `Target Format: ${targetExt.toUpperCase()}`,
    `Timestamp: ${new Date().toISOString()}`,
    `----------------------------------------`,
    ...lines,
  ].join('\n');

  return new Blob([outputText], { type: mimeType });
}

export async function runFileConversion(
  item: ConversionQueueItem,
  speed: ConversionSpeed,
  onProgress: (progress: number, stageLabel: string, point: TelemetryPoint) => void,
  signal: AbortSignal
): Promise<ConversionResult> {
  const targetDef = getFormatDefinition(item.targetExt);
  const totalSteps = 20;
  const stepDelayMs = speed === 'fast' ? 85 : speed === 'normal' ? 165 : 270;
  const startTime = performance.now();

  // Check if the document is corrupted (0-byte or explicitly flagged corrupted)
  if (item.fileSize === 0 || item.isCorrupted || item.options.simulateCorrupted) {
    await sleep(380, signal);
    throw new ConversionError(
      'Source document is corrupted (invalid container header or 0-byte payload) and cannot be converted.',
      true
    );
  }

  // Base throughput in Mbps depending on category & speed setting
  const baseMbps =
    speed === 'fast'
      ? 34.0
      : speed === 'normal'
      ? 22.5
      : 14.8;

  // Deterministic seed from item ID for realistic throughput curve
  const seed = item.id.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const recordedMbps: number[] = [];

  for (let step = 1; step <= totalSteps; step++) {
    await sleep(stepDelayMs, signal);
    const pct = Math.min(96, Math.round((step / totalSteps) * 96));
    const stage = getStageLabel(pct, item.sourceExt, item.targetExt, targetDef.category);
    const elapsedMs = Math.round(performance.now() - startTime);

    // Compute realistic throughput curve (ramps up during transcode, tapers on muxing)
    const ramp = Math.sin((step / totalSteps) * Math.PI);
    const harmonic = Math.sin(step * 0.85 + seed) * 4.2 + Math.cos(step * 1.4) * 2.1;
    const mbps = Number(Math.max(4.5, baseMbps * (0.65 + 0.55 * ramp) + harmonic).toFixed(2));
    recordedMbps.push(mbps);

    const point: TelemetryPoint = {
      step,
      elapsedMs,
      progress: pct,
      mbps,
      stage,
    };

    onProgress(pct, stage, point);

    if (item.options.simulateFailure && pct >= 52) {
      throw new ConversionError(
        `Transient codec buffer error while encoding .${item.targetExt.toUpperCase()} at ${pct}%. Source document is intact — click Retry to convert.`,
        false
      );
    }
  }

  let outputBlob: Blob;
  if (targetDef.category === 'image' || targetDef.category === 'vector') {
    outputBlob = await convertToImageBlob(item, targetDef.mimeType);
  } else if (targetDef.category === 'audio') {
    outputBlob = await buildPlayableAudioBlob(item.file, targetDef.mimeType, 4.0);
  } else if (targetDef.category === 'video') {
    outputBlob = await buildPlayableVideoBlob(item, targetDef.mimeType);
  } else {
    outputBlob = await convertDataOrDocumentBlob(item, targetDef.mimeType);
  }

  if (signal.aborted) {
    throw new DOMException('Conversion cancelled by user', 'AbortError');
  }

  const finalElapsed = Math.round(performance.now() - startTime);
  const finalMbps = Number((baseMbps * 0.92).toFixed(2));
  recordedMbps.push(finalMbps);

  onProgress(100, 'Finished', {
    step: totalSteps + 1,
    elapsedMs: finalElapsed,
    progress: 100,
    mbps: finalMbps,
    stage: 'Finished',
  });

  const avgMbps = Number(
    (recordedMbps.reduce((a, b) => a + b, 0) / Math.max(1, recordedMbps.length)).toFixed(2)
  );
  const peakMbps = Number(Math.max(...recordedMbps).toFixed(2));

  const outFileName = `${item.baseName}.${item.targetExt.toLowerCase()}`;
  return {
    blob: outputBlob,
    fileName: outFileName,
    size: outputBlob.size,
    avgMbps,
    peakMbps,
  };
}
